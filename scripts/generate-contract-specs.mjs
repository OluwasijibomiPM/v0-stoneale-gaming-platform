// Embeds each Soroban contract's interface (spec) in the app, so contract
// clients don't have to download the wasm from the network at runtime.
// Run after `stellar contract build` in soroban/: pnpm contracts:specs
import { readFileSync, writeFileSync } from "fs"
import { contract } from "@stellar/stellar-sdk"

const CONTRACTS = ["rewards", "achievements", "tournaments"]

const entries = CONTRACTS.map((name) => {
  const wasm = readFileSync(new URL(`../soroban/target/wasm32v1-none/release/${name}.wasm`, import.meta.url))
  const spec = contract.Spec.fromWasm(wasm)
  const lines = spec.entries.map((entry) => `    "${entry.toXDR("base64")}",`).join("\n")
  return `  ${name}: [\n${lines}\n  ],`
})

const output = `// Generated by scripts/generate-contract-specs.mjs. Do not edit.

export const CONTRACT_SPECS = {
${entries.join("\n")}
} as const

export type ContractName = keyof typeof CONTRACT_SPECS
`

writeFileSync(new URL("../lib/stellar/contract-specs.ts", import.meta.url), output)
console.log(`Wrote specs for ${CONTRACTS.join(", ")}`)
